#!/bin/bash
echo "#######################################################################"
id
echo "#######################################################################"
uname -a
echo "#######################################################################"
lsb_release -a || true
echo "#######################################################################"
pwd
echo "#######################################################################"
ls -ld "$(pwd)"
echo "#######################################################################"
touch out; ls -ld out
echo "#######################################################################"
wget --no-verbose https://github.com/dugoh/386bsd0.1/raw/master/BSD.tar.bz2
echo "#######################################################################"
file BSD.tar.bz2
echo "#######################################################################"
exit
